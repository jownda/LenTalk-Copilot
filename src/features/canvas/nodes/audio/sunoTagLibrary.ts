/**
 * Suno 风格标签库 —— 供「风格标签」(`style`) 与「排除风格」(`negative_tags`)
 * 两个字段做点选。
 *
 * 为什么是**数据模块**而不是 i18n 文案：
 * 这些词最终会**原样写进提示词**交给模型（`style` → Suno `tags`），它们属于
 * 「内容」而不是「界面外壳」—— 和模型名、音色名同性质，因此按文档 0.1 的
 * 口径不走 i18n。分组标题才是界面文案，走 `node.audioGen.suno.tagGroups.*`。
 *
 * 三条维护约定：
 *   1. **同一个标签只出现在一个分组里**。批量勾选是「按值 toggle」的，
 *      跨组重复会让「点 A 组的高亮跟着 B 组一起亮」。有单测锁这条。
 *   2. 组内顺序＝从常用到冷门，不按拼音排 —— 用户是从上往下扫的。
 *   3. 中英混排是刻意的：国际化曲风（City Pop / Lo-fi / K-Pop）保留英文原名，
 *      中文表达为主的（古风 / 治愈 / 二胡）用中文。Suno 对两种写法都能识别。
 */

export interface SunoTagGroup {
  /** 稳定标识，同时用于 i18n 的 `...tagGroups.<key>`。 */
  key: string;
  /** 分组标题的 i18n key（完整 key，调用方直接 t()）。 */
  labelKey: string;
  tags: readonly string[];
}

const GROUP_LABEL_PREFIX = "node.audioGen.suno.tagGroups.";

function group(key: string, tags: readonly string[]): SunoTagGroup {
  return { key, labelKey: `${GROUP_LABEL_PREFIX}${key}`, tags };
}

