/** 界面里两个字段的分隔符是**逗号**；解析时容忍中文逗号/顿号/分号，避免
 *  用户从别处粘过来的一串被当成一个巨型标签。 */
const TAG_SEPARATOR = /[,，、;；]+/;

/** 把字段值拆成标签数组（去空白、丢空项）。 */
export function parseTagList(value: string): string[] {
  if (!value) return [];
  return value
    .split(TAG_SEPARATOR)
    .map((item) => item.trim())
    .filter((item) => item.length > 0);
}

/** 用统一的 `", "` 回写，保证手填与点选产生同一形状。 */
export function joinTagList(tags: readonly string[]): string {
  return tags.join(", ");
}

/** 是否存在该标签（决定 chip 的高亮，也是 toggle 的判据）。 */
export function hasTag(value: string, tag: string): boolean {
  return parseTagList(value).includes(tag);
}

/** 点一下加入、再点一下移除。已存在时保持**原位置**移除，不打乱用户手填的顺序。 */
export function toggleTag(value: string, tag: string): string {
  const tags = parseTagList(value);
  const index = tags.indexOf(tag);
  if (index >= 0) {
    tags.splice(index, 1);
  } else {
    tags.push(tag);
  }
  return joinTagList(tags);
}

/** 已选数量，用于折叠态的角标。 */
export function countTags(value: string): number {
  return parseTagList(value).length;
}
