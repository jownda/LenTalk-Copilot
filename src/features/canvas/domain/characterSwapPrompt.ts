/**
 * 「角色替换」节点的一键提示词模板。
 *
 * ## 为什么要有这份模板
 *
 * 应用作者在 RunningHub 上写的那版提示词是围绕**一个具体角色**写的 ——
 * 「乌黑长发及腰、自然中分且发尾微卷，着装为象牙白缎面细吊带长裙，垂顺及踝，
 * 肩带以银色金属圆环与肩部衔接，脚穿白色细带低跟凉鞋」。这段描述对那位角色非常准，
 * 但换成任何别的角色都必须整段重写，否则模型会把衣服、发型、鞋一起"换"成那一套。
 *
 * 所以这里做三件事：
 * 1. **抽走外观描述**，改成「以参考图为唯一依据」的通用措辞；
 * 2. **保留原提示词的骨架**：换谁 → 保什么 → 一致什么 → 不许改什么，四段递进；
 * 3. 把原来散落在句子里的约束（场景/运镜/光线/动作/位置/透视）归成可读的分句，
 *    方便用户只删自己不要的那一条。
 *
 * ## 两处不能改
 *
 * - `<Image 1>` 与 `video 1` 是应用内部对素材的引用名，改了就指不到图和视频；
 * - 「保持场景、运镜、动作不变」这一段是这支应用的核心约束（它是**换人**，
 *   不是重绘），删掉之后模型会开始自由发挥镜头和构图。
 */
export const CHARACTER_SWAP_PROMPT_TEMPLATE = `将 video 1 中的人物替换为 <Image 1> 中的角色。

请以 <Image 1> 作为替换角色的唯一身份与外观依据：面部特征、面部结构、肤色、发型与发色、身体比例、服装款式与配饰细节，全部严格以参考图为准，不得自行发挥或替换。若参考图中包含同一角色的多个视角，应视为同一个完整、统一的角色形象。

保持原视频的场景、环境、运镜、构图、光线效果、阴影效果、节奏、角色动作、姿势、视线方向及整体表演完全不变。替换后的角色应能自然完成与原角色完全相同的动作。

在整个视频中保持角色形象的一致性：面部表情、发型、服装、身体比例与整体形象须在所有镜头中保持稳定。同时确保原角色的位置、尺寸比例、透视关系及其与环境的互动保持不变。

请勿修改任何其他人、物体、背景、运镜或场景元素，不得新增或删除任何物体。最终效果应如同原视频从一开始就由 <Image 1> 中的角色出演。`;

/**
 * 模板里必须出现的素材引用名。
 *
 * 单独导出是为了让测试盯住它：这两个标记一旦被"美化"成「参考图」「原视频」之类的
 * 中文描述，提示词读起来更顺，但应用侧就完全认不出素材了 —— 表现为生成的视频跟
 * 参考图毫无关系，而且没有任何报错。
 */
export const CHARACTER_SWAP_PROMPT_MARKERS = ['<Image 1>', 'video 1'] as const;

/**
 * 决定这次实际发出去的提示词：**留空就用通用模板**。
 *
 * 早先的实现是「留空 → 不提交提示词节点 → 应用用它自带的模板」，但那个内置模板是
 * 围着一位具体角色写的（乌黑长发、象牙白缎面吊带长裙、白色细带凉鞋）。留空看着像
 * "不做干预"，实际是**把那一整套外观强行套到任意角色身上** —— 换谁都会被改衣服改发型。
 * 所以在画布这一侧把默认值换成了通用模板，内置模板不再作为默认路径。
 *
 * 用户自己写的提示词原样保留（只去首尾空白），不做任何拼装 —— 他可能就想精确控制。
 */
export function resolveCharacterSwapPrompt(prompt: string | null | undefined): string {
  const trimmed = typeof prompt === 'string' ? prompt.trim() : '';
  return trimmed || CHARACTER_SWAP_PROMPT_TEMPLATE;
}
