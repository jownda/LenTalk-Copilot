/**
 * 素材库条目名 ⇄ 磁盘文件名的换算规则。
 *
 * 早期落盘用的是内容哈希（md5）或 uuid，于是「素材库里叫『商品头图』，磁盘上叫
 * `3f2b…d9.png`」—— 用户去访达里看一眼就对不上，重命名也只改显示名，文件岿然不动。
 * 现在统一成：**磁盘文件名 = 素材名（净化非法字符）+ 扩展名**。
 *
 * 这里的前端实现必须和 Rust 侧 `sanitize_file_stem` 逐字符对齐：前端用它预测目标名，
 * 两边规则一旦分叉，就会在启动对齐时反复改名（名字永远「对不上」）。
 */

/** 文件名主干最大长度（字符）。Rust 侧同值，超长在部分文件系统上会被静默截断。 */
export const ASSET_FILE_STEM_MAX_CHARS = 80;

/** 名字被净化成空时的兜底主干。 */
export const ASSET_FILE_STEM_FALLBACK = '素材';

const RESERVED_CHARACTERS = new Set(['/', '\\', ':', '*', '?', '"', '<', '>', '|']);

/** Windows 保留设备名：叫 `CON` / `NUL` 的文件根本创建不出来。Rust 侧同表。 */
const RESERVED_FILE_STEMS = new Set([
  'con', 'prn', 'aux', 'nul',
  'com1', 'com2', 'com3', 'com4', 'com5', 'com6', 'com7', 'com8', 'com9',
  'lpt1', 'lpt2', 'lpt3', 'lpt4', 'lpt5', 'lpt6', 'lpt7', 'lpt8', 'lpt9',
]);

/** 把素材名收敛成安全的文件名主干（不含扩展名）。 */
export function sanitizeAssetFileStem(raw: string): string {
  let mapped = '';
  for (const character of raw ?? '') {
    const code = character.codePointAt(0) ?? 0;
    if (code < 0x20 || code === 0x7f) {
      continue;
    }
    mapped += RESERVED_CHARACTERS.has(character) ? '-' : character;
  }

  const collapsed = mapped.split(/\s+/).filter(Boolean).join(' ');
  const trimmed = collapsed.replace(/^[.\s]+/, '').replace(/[.\s]+$/, '');
  const limited = Array.from(trimmed).slice(0, ASSET_FILE_STEM_MAX_CHARS).join('');
  const result = limited.replace(/[.\s]+$/, '');
  if (!result) return ASSET_FILE_STEM_FALLBACK;
  return RESERVED_FILE_STEMS.has(result.toLowerCase()) ? `_${result}` : result;
}

/**
 * 判断磁盘上的名字是否是「程序自动生成」的（内容哈希 / uuid / 备份临时名 / 画布临时名）。
 *
 * 只有这类名字才允许在启动时自动改成素材名：用户自己起的名字（哪怕是旧版本导入的
 * `IMG_1234`）一律不动，避免把人家整理好的文件目录搅乱。
 */
export function isAutoGeneratedAssetFileStem(stem: string): boolean {
  const value = (stem ?? '').trim();
  if (!value) return true;
  // 视频缩略图是「<视频名>.<扩展名>.png」：把最后一段扩展名剥掉再判一次，
  // 否则 `abc…def.mp4.png` 永远认不出来（缩略图就永远留着一串哈希名）。
  const withoutOuterExtension = value.replace(/\.[a-z0-9]{1,6}$/i, '');
  return matchesAutoGeneratedPattern(value) || matchesAutoGeneratedPattern(withoutOuterExtension);
}

function matchesAutoGeneratedPattern(value: string): boolean {
  if (!value) return false;
  if (/^[0-9a-f]{32}$/i.test(value)) return true; // md5
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value)) return true; // uuid
  if (/^backup-[0-9a-z-]+$/i.test(value)) return true; // 分块写入 / 备份恢复
  if (/^import-\d+-[0-9a-z]+$/i.test(value)) return true; // 备份恢复
  if (/^canvas-(image|audio|video)-\d+$/i.test(value)) return true; // 画布「添加到素材库」
  return false;
}

const NON_FILE_SOURCE = /^(data|blob|asset|http|https):/i;

/** 从路径里取文件名（含扩展名）；data:/blob:/asset:/http(s) 等非文件来源返回空串。 */
export function fileNameFromPath(source: string | null | undefined): string {
  const value = (source ?? '').trim();
  if (!value || NON_FILE_SOURCE.test(value)) return '';
  const withoutQuery = value.split(/[?#]/, 1)[0] ?? '';
  const segments = withoutQuery.split(/[\\/]/);
  return segments[segments.length - 1] ?? '';
}

/** 从路径里取文件名主干（去扩展名）；非文件来源返回空串。 */
export function fileStemFromPath(source: string | null | undefined): string {
  const name = fileNameFromPath(source);
  if (!name) return '';
  const index = name.lastIndexOf('.');
  return index > 0 ? name.slice(0, index) : name;
}

/** 从路径里取扩展名（小写，无点）；非文件来源返回空串。 */
export function fileExtensionFromPath(source: string | null | undefined): string {
  const name = fileNameFromPath(source);
  const index = name.lastIndexOf('.');
  return index > 0 ? name.slice(index + 1).toLowerCase() : '';
}

/**
 * 素材库条目的显示名与磁盘文件名是否一致（不含扩展名比较）。
 *
 * `sourceFileName` 早期存的是「原始上传文件名」，和条目名可以完全不同；现在两者
 * 必须同步，这个函数就是校验口径。
 */
export function isAssetFileNameAligned(asset: {
  name: string;
  sourcePath: string;
  sourceFileName?: string | null;
}): boolean {
  const stem = fileStemFromPath(asset.sourcePath);
  if (!stem) return true; // data:/http: 来源没有磁盘文件名，不算不一致
  return stem === sanitizeAssetFileStem(asset.name);
}
