import { describe, expect, it } from 'vitest';

import {
  ASSET_FILE_STEM_FALLBACK,
  ASSET_FILE_STEM_MAX_CHARS,
  fileNameFromPath,
  fileExtensionFromPath,
  fileStemFromPath,
  isAssetFileNameAligned,
  isAutoGeneratedAssetFileStem,
  sanitizeAssetFileStem,
} from './assetFileNaming';

describe('sanitizeAssetFileStem', () => {
  it('把非法字符换成短横线', () => {
    expect(sanitizeAssetFileStem('画布图片 10:08:32')).toBe('画布图片 10-08-32');
    expect(sanitizeAssetFileStem('a/b\\c*d?e"f<g>h|i')).toBe('a-b-c-d-e-f-g-h-i');
  });

  it('折叠空白并去掉首尾点和空格(Windows/macOS 都不接受)', () => {
    expect(sanitizeAssetFileStem('  多   空格  ')).toBe('多 空格');
    expect(sanitizeAssetFileStem('..封面. .')).toBe('封面');
  });

  it('净化后为空时用兜底名', () => {
    expect(sanitizeAssetFileStem('   ')).toBe(ASSET_FILE_STEM_FALLBACK);
    expect(sanitizeAssetFileStem('....')).toBe(ASSET_FILE_STEM_FALLBACK);
  });

  it('Windows 保留设备名前面加下划线', () => {
    expect(sanitizeAssetFileStem('con')).toBe('_con');
    expect(sanitizeAssetFileStem('NUL')).toBe('_NUL');
  });

  it('结果稳定且不超长(否则启动对齐会反复改名)', () => {
    const once = sanitizeAssetFileStem('商品头图');
    expect(sanitizeAssetFileStem(once)).toBe(once);

    const long = sanitizeAssetFileStem('长'.repeat(200));
    expect(Array.from(long)).toHaveLength(ASSET_FILE_STEM_MAX_CHARS);
    expect(sanitizeAssetFileStem(long)).toBe(long);
  });
});

describe('isAutoGeneratedAssetFileStem', () => {
  it('认得出历史遗留的自动命名', () => {
    expect(isAutoGeneratedAssetFileStem('3f2b1c9d8e7a6b5c4d3e2f1a0b9c8d7e')).toBe(true); // md5
    expect(isAutoGeneratedAssetFileStem('0f8fad5b-d9cb-469f-a165-70867728950e')).toBe(true); // uuid
    expect(isAutoGeneratedAssetFileStem('backup-12ab-34cd')).toBe(true);
    expect(isAutoGeneratedAssetFileStem('canvas-image-1759123456789')).toBe(true);
  });

  it('用户自己起的名字不动', () => {
    expect(isAutoGeneratedAssetFileStem('商品头图')).toBe(false);
    expect(isAutoGeneratedAssetFileStem('IMG_1234')).toBe(false);
    expect(isAutoGeneratedAssetFileStem('场景-客厅')).toBe(false);
  });

  it('视频缩略图("视频哈希.mp4.png")也认得出', () => {
    expect(isAutoGeneratedAssetFileStem('00f701691f8d4cd8997beee0404bbdb6.mp4')).toBe(true);
    expect(isAutoGeneratedAssetFileStem('a1b2c3d4-0000-4000-8000-000000000000.mp4')).toBe(true);
    expect(isAutoGeneratedAssetFileStem('开场镜头.mp4')).toBe(false);
  });
});

describe('路径解析', () => {
  it('兼容 macOS 与 Windows 分隔符', () => {
    expect(fileNameFromPath('/Users/a/Library/library-assets/商品头图.png')).toBe('商品头图.png');
    expect(fileNameFromPath(String.raw`C:\Users\a\library-assets\商品头图.png`)).toBe('商品头图.png');
    expect(fileStemFromPath('/x/商品头图.png')).toBe('商品头图');
    expect(fileExtensionFromPath('/x/商品头图.PNG')).toBe('png');
  });

  it('非文件来源(内联/远端)不当作文件名', () => {
    expect(fileNameFromPath('data:image/png;base64,AAAA')).toBe('');
    expect(fileNameFromPath('https://cdn.example.com/a.png?x=1')).toBe('');
    expect(fileStemFromPath('asset://localhost/a.png')).toBe('');
  });

  it('带查询串的本地路径仍能取到文件名', () => {
    expect(fileNameFromPath('/x/a.png?v=2')).toBe('a.png');
  });
});

describe('isAssetFileNameAligned', () => {
  it('磁盘文件名主干等于净化后的素材名才算一致', () => {
    expect(
      isAssetFileNameAligned({ name: '商品头图', sourcePath: '/lib/商品头图.png' }),
    ).toBe(true);
    expect(
      isAssetFileNameAligned({ name: '商品头图', sourcePath: '/lib/3f2b1c9d8e7a6b5c4d3e2f1a0b9c8d7e.png' }),
    ).toBe(false);
    // data URL 没有磁盘文件名,不算不一致
    expect(
      isAssetFileNameAligned({ name: '商品头图', sourcePath: 'data:image/png;base64,AA' }),
    ).toBe(true);
  });
});
