const LEGACY_STORAGE_KEY = 'storyboard-asset-library-v1-v1';

/** 拿不到原文件扩展名时的兜底（浏览器模式下的 data URL 素材）。 */
const DEFAULT_ASSET_FILE_EXTENSIONS: Record<string, string> = {
  image: 'png',
  video: 'mp4',
  audio: 'mp3',
};

const BUILTIN_CATEGORY_DEFINITIONS = [
  { key: 'characters', name: '角色' },
  { key: 'scenes', name: '场景' },
  { key: 'props', name: '道具' },
  { key: 'audio', name: '音频' },
] as const;

interface AssetLibraryStore extends AssetLibraryState {
  isHydrated: boolean;
  hydrate: () => Promise<void>;
  setActiveLibrary: (libraryId: string) => void;
  createLibrary: (name: string) => string;
  renameLibrary: (libraryId: string, name: string) => void;
  deleteLibrary: (libraryId: string) => void;
  addAssets: (assets: LibraryAsset[]) => void;
  upsertAssets: (assets: LibraryAsset[]) => void;
  deleteAssets: (assetIds: string[]) => void;
  /**
   * 重命名素材：素材库里的名字和磁盘上的原素材文件名一起改。
   *
   * 桌面端会真的把 `library-assets/` 里的文件改成新名字（扩展名不变），并把画布、
   * 工程、模板里指向旧路径的引用一并搬家 —— 否则「改名 = 图片全部白屏」。
   */
  renameAsset: (assetId: string, name: string) => Promise<void>;
  setAssetTags: (assetId: string, tags: string[]) => void;
  classifyAssets: (assetIds: string[]) => number;
  addCategory: (libraryId: string, name: string, parentId?: string | null) => string;
  renameCategory: (categoryId: string, name: string) => void;
  deleteCategory: (categoryId: string) => void;
  moveAssetsToCategory: (assetIds: string[], categoryId: string | null) => void;
}

let persistQueue = Promise.resolve();

function createId(prefix: string): string {
  return `${prefix}-${uuid().slice(0, 12)}`;
}

function defaultState(): AssetLibraryState {
  const libraryId = 'library-default';
  return {
    libraries: [{ id: libraryId, name: '我的素材库', createdAt: 0 }],
    categories: createBuiltinCategories(libraryId),
    assets: [],
    activeLibraryId: libraryId,
  };
}

function createBuiltinCategories(libraryId: string): AssetCategory[] {
  return BUILTIN_CATEGORY_DEFINITIONS.map(({ key, name }) => ({
    id: libraryId === 'library-default' ? `category-${key}` : `category-${libraryId}-${key}`,
    libraryId,
    name,
    builtin: true,
    createdAt: 0,
  }));
}

function ensureBuiltinCategories(libraries: AssetLibrary[], categories: AssetCategory[]): AssetCategory[] {
  const next = [...categories];
  for (const library of libraries) {
    for (const definition of BUILTIN_CATEGORY_DEFINITIONS) {
      const existing = next.find(
        (category) => category.libraryId === library.id && category.name === definition.name && !category.parentId
      );
      if (existing) {
        if (!existing.builtin) {
          const index = next.indexOf(existing);
          next[index] = { ...existing, builtin: true };
        }
        continue;
      }
      next.push(...createBuiltinCategories(library.id).filter((category) => category.name === definition.name));
    }
  }
  return next;
}

function readBrowserState(): AssetLibraryState {
  try {
    const value = localStorage.getItem(ASSET_LIBRARY_STORAGE_KEY);
    return value ? normalizeState(JSON.parse(value) as AssetLibraryState) : defaultState();
  } catch {
    return defaultState();
  }
}

function normalizeState(state: AssetLibraryState): AssetLibraryState {
  if (!Array.isArray(state.libraries) || state.libraries.length === 0) return defaultState();
  const libraries = state.libraries.filter((library) => Boolean(library?.id));
  if (libraries.length === 0) return defaultState();
  const libraryIds = new Set(libraries.map((library) => library.id));
  const rawCategories = (Array.isArray(state.categories) ? state.categories : []).filter(
    (category) => category?.id && libraryIds.has(category.libraryId)
  );
  const categories = ensureBuiltinCategories(libraries, rawCategories);
  const categoryIds = new Set(categories.map((category) => category.id));
  const assets = (Array.isArray(state.assets) ? state.assets : [])
    .filter((asset) => asset?.id && asset.sourcePath && libraryIds.has(asset.libraryId))
    .map((asset) => ({
      ...asset,
      categoryId: asset.categoryId && categoryIds.has(asset.categoryId) ? asset.categoryId : null,
      mediaType: ['image', 'video', 'audio'].includes(asset.mediaType) ? asset.mediaType : 'image',
      tags: Array.isArray(asset.tags) ? asset.tags.filter(Boolean) : [],
    })) as LibraryAsset[];
  return {
    libraries,
    categories,
    assets,
    activeLibraryId: libraryIds.has(state.activeLibraryId) ? state.activeLibraryId : libraries[0].id,
  };
}

function legacyMigration(): AssetLibraryState | null {
  try {
    const raw = localStorage.getItem(LEGACY_STORAGE_KEY);
    if (!raw) return null;
    const legacy = JSON.parse(raw) as {
      assets?: Array<{
        id?: string;
        categoryId?: string | null;
        imageUrl?: string;
        previewImageUrl?: string;
        aspectRatio?: string;
        sourceFileName?: string | null;
        name?: string;
        createdAt?: number;
      }>;
      categories?: Array<{ id?: string; name?: string; createdAt?: number }>;
    };
    if (!Array.isArray(legacy.assets) || legacy.assets.length === 0) return null;
    const next = defaultState();
    const libraryId = next.activeLibraryId;
    next.categories = (legacy.categories ?? [])
      .filter((category) => category.id)
      .map((category) => ({
        id: category.id as string,
        libraryId,
        name: category.name?.trim() || '未分类',
        createdAt: category.createdAt ?? Date.now(),
      }));
    next.assets = legacy.assets
      .filter((asset) => asset.id && asset.imageUrl)
      .map((asset) => ({
        id: asset.id as string,
        libraryId,
        categoryId: asset.categoryId ?? null,
        name: asset.name?.trim() || '未命名素材',
        mediaType: 'image' as const,
        sourcePath: asset.imageUrl as string,
        previewImageUrl: asset.previewImageUrl ?? asset.imageUrl ?? null,
        aspectRatio: asset.aspectRatio ?? '1:1',
        sourceFileName: asset.sourceFileName ?? null,
        tags: [],
        createdAt: asset.createdAt ?? Date.now(),
      }));
    return normalizeState(next);
  } catch {
    return null;
  }
}

function persist(state: AssetLibraryState): void {
  const snapshot = normalizeState(state);
  persistQueue = persistQueue
    .catch(() => undefined)
    .then(async () => {
      if (isTauri()) {
        await saveAssetLibraryState(snapshot);
      } else {
        localStorage.setItem(ASSET_LIBRARY_STORAGE_KEY, JSON.stringify(snapshot));
      }
    })
    .catch((error) => console.warn('[assetLibrary] persist failed', error));
}

function updateStore(
  set: (partial: Partial<AssetLibraryStore>) => void,
  next: AssetLibraryState
): void {
  const normalized = normalizeState(next);
  set(normalized);
  persist(normalized);
}

/**
 * 启动时把「程序自动生成」的磁盘文件名对齐到素材名。
 *
 * 老版本的素材文件叫 `3f2b…d9.png` / `backup-xxx.mp4` / `canvas-image-1759….png`，
 * 素材库里却叫「商品头图」—— 用户去访达里根本对不上号，改名也改不到文件。这里把
 * 这类文件一次性改成素材名（用户自己起的名字不碰），并把画布/工程/模板里的引用搬家。
 *
 * 幂等：改名成功后文件名不再命中「自动生成」规则，后续启动不会再动它。
 */
async function alignAssetFileNamesOnHydrate(): Promise<void> {
  if (!isTauri()) return;
  const state = useAssetLibraryStore.getState();
  if (state.assets.length === 0) return;

  const pathMap = new Map<string, string>();
  const assets: LibraryAsset[] = [];
  let changed = false;

  for (const asset of state.assets) {
    let next = asset;
    const stem = fileStemFromPath(asset.sourcePath);
    if (stem && isAutoGeneratedAssetFileStem(stem)) {
      const shared = state.assets.some(
        (item) => item.id !== asset.id && item.sourcePath === asset.sourcePath,
      );
      try {
        const renamed = await renameLibraryAssetFile(
          asset.sourcePath,
          sanitizeAssetFileStem(asset.name),
          shared,
        );
        if (renamed && renamed !== asset.sourcePath) {
          const alignedName = sanitizeAssetFileStem(asset.name);
          // 同一个旧文件可能被多条素材共用（共用时走的是复制）：只保留第一次的映射，
          // 否则后来的条目会把之前的映射覆盖掉，引用方全被指到后一个副本上。
          if (!pathMap.has(asset.sourcePath)) {
            pathMap.set(asset.sourcePath, renamed);
          }
          next = {
            ...next,
            // 重名时落盘会加 `(2)` 序号，名字跟着真实文件走，避免下次启动再算一遍。
            name: fileStemFromPath(renamed) || alignedName,
            sourcePath: renamed,
            sourceFileName: fileNameFromPath(renamed) || next.sourceFileName || null,
          };
          changed = true;
        }
      } catch (error) {
        console.warn('[assetLibrary] align asset file name failed', asset.sourcePath, error);
      }
    }

    const previewSource = next.previewImageUrl ?? '';
    const previewStem = fileStemFromPath(previewSource);
    if (previewStem && isAutoGeneratedAssetFileStem(previewStem)) {
      const shared = state.assets.some(
        (item) => item.id !== asset.id && item.previewImageUrl === asset.previewImageUrl,
      );
      try {
        const renamedPreview = await renameLibraryAssetFile(
          previewSource,
          `${next.name}.preview`,
          shared,
        );
        if (renamedPreview && renamedPreview !== previewSource) {
          if (!pathMap.has(previewSource)) {
            pathMap.set(previewSource, renamedPreview);
          }
          next = { ...next, previewImageUrl: renamedPreview };
          changed = true;
        }
      } catch (error) {
        console.warn('[assetLibrary] align asset preview name failed', previewSource, error);
      }
    }

    assets.push(next);
  }

  if (!changed) return;
  updateStore((partial) => useAssetLibraryStore.setState(partial), { ...state, assets });
  if (pathMap.size > 0) {
    try {
      await applyAssetPathRemap(pathMap);
    } catch (error) {
      console.warn('[assetLibrary] remap references after align failed', error);
    }
  }
}

function suggestCategoryId(asset: LibraryAsset, categories: AssetCategory[]): string | null {  const searchable = [asset.name, asset.sourceFileName ?? '', ...asset.tags].join(' ').toLocaleLowerCase();
  const groups: Array<{ category: RegExp; clues: RegExp }> = [
    { category: /角色|人物|character|portrait/i, clues: /角色|人物|肖像|头像|男|女|儿童|老人|character|portrait|person|actor/i },
    { category: /场景|背景|scene|background/i, clues: /场景|背景|室内|室外|街道|建筑|城市|森林|房间|scene|background|street|city|room|landscape/i },
    { category: /道具|物品|props?/i, clues: /道具|物品|武器|车辆|汽车|服装|家具|食物|prop|weapon|vehicle|car|clothing|furniture/i },
    { category: /视频|video/i, clues: /video|视频|镜头|shot|clip/i },
    { category: /音频|音效|配音|audio/i, clues: /audio|音频|音效|配音|music|voice|sound/i },
  ];
  const matchingGroup = groups.find((group) => group.clues.test(searchable));
  if (!matchingGroup) return null;
  return categories.find((category) => matchingGroup.category.test(category.name))?.id ?? null;
}

export const useAssetLibraryStore = create<AssetLibraryStore>((set, get) => ({
  ...defaultState(),
  isHydrated: false,

  hydrate: async () => {
    if (get().isHydrated) return;
    try {
      let state = isTauri() ? await loadAssetLibraryState() : readBrowserState();
      state = normalizeState(state);
      if (state.assets.length === 0) {
        const migrated = legacyMigration();
        if (migrated) {
          state = migrated;
          persist(state);
        }
      }
      set({ ...state, isHydrated: true });
      // 磁盘文件名对齐（老数据的一次性搬家）放到水合之后异步跑，不阻塞首屏。
      void alignAssetFileNamesOnHydrate();
    } catch (error) {
      console.warn('[assetLibrary] hydrate failed', error);
      set({ ...readBrowserState(), isHydrated: true });
    }
  },

  setActiveLibrary: (libraryId) => {
    const state = get();
    if (!state.libraries.some((library) => library.id === libraryId)) return;
    updateStore(set, { ...state, activeLibraryId: libraryId });
  },

  createLibrary: (name) => {
    const state = get();
    const now = Date.now();
    const library: AssetLibrary = {
      id: createId('library'),
      name: name.trim() || '新素材库',
      createdAt: now,
    };
    updateStore(set, {
      ...state,
      libraries: [...state.libraries, library],
      categories: [...state.categories, ...createBuiltinCategories(library.id)],
      activeLibraryId: library.id,
    });
    return library.id;
  },

  renameLibrary: (libraryId, name) => {
    const state = get();
    const value = name.trim();
    if (!value) return;
    updateStore(set, {
      ...state,
      libraries: state.libraries.map((library) =>
        library.id === libraryId ? { ...library, name: value } : library
      ),
    });
  },

  deleteLibrary: (libraryId) => {
    const state = get();
    if (state.libraries.length <= 1) return;
    const libraries = state.libraries.filter((library) => library.id !== libraryId);
    updateStore(set, {
      libraries,
      categories: state.categories.filter((category) => category.libraryId !== libraryId),
      assets: state.assets.filter((asset) => asset.libraryId !== libraryId),
      activeLibraryId: state.activeLibraryId === libraryId ? libraries[0].id : state.activeLibraryId,
    });
  },

  addAssets: (assets) => {
    const state = get();
    updateStore(set, { ...state, assets: [...state.assets, ...assets] });
  },

  upsertAssets: (assets) => {
    if (assets.length === 0) return;
    const state = get();
    const incoming = new Map(assets.map((asset) => [asset.id, asset]));
    const retained = state.assets.filter((asset) => !incoming.has(asset.id));
    updateStore(set, { ...state, assets: [...retained, ...assets] });
  },

  deleteAssets: (assetIds) => {
    const ids = new Set(assetIds);
    const state = get();
    updateStore(set, { ...state, assets: state.assets.filter((asset) => !ids.has(asset.id)) });
  },

  renameAsset: async (assetId, name) => {
    const state = get();
    const asset = state.assets.find((item) => item.id === assetId);
    if (!asset) return;

    const extensionHint =
      fileExtensionFromPath(asset.sourcePath)
      || fileExtensionFromPath(asset.sourceFileName ?? '')
      || DEFAULT_ASSET_FILE_EXTENSIONS[asset.mediaType];
    // 用户可能连着扩展名一起改（「商品头图.png」）：先剥掉再当文件名主干，
    // 否则会落成「商品头图.png.png」，素材名和文件名又对不上了。
    let value = name.trim();
    if (extensionHint && value.toLowerCase().endsWith(`.${extensionHint.toLowerCase()}`)) {
      value = value.slice(0, value.length - extensionHint.length - 1).trim();
    }
    if (!value) return;
    // 名字本身也过一遍净化：素材名带 `/`、`:` 时如果不净化，磁盘上只能落成 `-`，
    // 两边又对不上。净化后名字 = 文件名主干，这条不变式才真正成立。
    value = sanitizeAssetFileStem(value);

    const nextAsset: LibraryAsset = { ...asset, name: value };
    const pathMap = new Map<string, string>();

    if (isTauri()) {
      // 旧版本按内容哈希去重，同一份文件可能被多条素材共用：共用时只能复制、不能搬走。
      const sourceSharedWithOthers = state.assets.some(
        (item) => item.id !== assetId && item.sourcePath === asset.sourcePath,
      );
      try {
        const renamedSource = await renameLibraryAssetFile(asset.sourcePath, value, sourceSharedWithOthers);
        if (renamedSource && renamedSource !== asset.sourcePath) {
          pathMap.set(asset.sourcePath, renamedSource);
          nextAsset.sourcePath = renamedSource;
        }
      } catch (error) {
        // 素材文件不在素材库目录（抽帧结果直接落在画布的 images 目录就是这种），
        // 没法原地改名 —— 复制一份进素材库目录，让素材真正拥有自己名字的文件。
        console.warn('[assetLibrary] rename asset file failed, trying copy', asset.sourcePath, error);
        if (fileNameFromPath(asset.sourcePath)) {
          try {
            const copied = await persistLibraryAssetFile(asset.sourcePath, extensionHint, value);
            pathMap.set(asset.sourcePath, copied);
            nextAsset.sourcePath = copied;
          } catch (copyError) {
            console.warn('[assetLibrary] copy asset file failed', asset.sourcePath, copyError);
          }
        }
      }

      if (asset.previewImageUrl) {
        const previewSharedWithOthers = state.assets.some(
          (item) => item.id !== assetId && item.previewImageUrl === asset.previewImageUrl,
        );
        try {
          const renamedPreview = await renameLibraryAssetFile(
            asset.previewImageUrl,
            `${value}.preview`,
            previewSharedWithOthers,
          );
          if (renamedPreview && renamedPreview !== asset.previewImageUrl) {
            pathMap.set(asset.previewImageUrl, renamedPreview);
            nextAsset.previewImageUrl = renamedPreview;
          }
        } catch (error) {
          console.warn('[assetLibrary] rename asset preview failed', asset.previewImageUrl, error);
        }
      }
    }

    // 磁盘上没改名（浏览器模式 / 文件不在素材库目录）时，仍把「原始文件名」对齐到新名字，
    // 否则画布节点按文件名生成的标题会一直停在老名字上。
    const renamedFileName = fileNameFromPath(nextAsset.sourcePath);
    if (renamedFileName && nextAsset.sourcePath !== asset.sourcePath) {
      // 磁盘上真的换了文件：以真实文件名为准（重名时会被加 `(2)` 后缀）。
      nextAsset.name = fileStemFromPath(nextAsset.sourcePath) || value;
      nextAsset.sourceFileName = renamedFileName;
    } else if (renamedFileName) {
      nextAsset.sourceFileName = renamedFileName;
    } else {
      nextAsset.sourceFileName = `${value}.${extensionHint || DEFAULT_ASSET_FILE_EXTENSIONS[asset.mediaType]}`;
    }

    updateStore(set, {
      ...state,
      assets: state.assets.map((item) => (item.id === assetId ? nextAsset : item)),
    });

    if (pathMap.size > 0) {
      // 参考文献搬家放到微任务里：先让界面上的新名字立刻生效，再慢慢改工程/模板。
      void applyAssetPathRemap(pathMap).catch((error) => {
        console.warn('[assetLibrary] remap asset references failed', error);
      });
    }
  },

  setAssetTags: (assetId, tags) => {
    const state = get();
    const normalizedTags = [...new Set(tags.map((tag) => tag.trim()).filter(Boolean))];
    updateStore(set, {
      ...state,
      assets: state.assets.map((asset) => asset.id === assetId ? { ...asset, tags: normalizedTags } : asset),
    });
  },

  classifyAssets: (assetIds) => {
    const ids = new Set(assetIds);
    const state = get();
    let changed = 0;
    const assets = state.assets.map((asset) => {
      if (!ids.has(asset.id)) return asset;
      const targetCategoryId = suggestCategoryId(
        asset,
        state.categories.filter((category) => category.libraryId === asset.libraryId)
      );
      if (!targetCategoryId || targetCategoryId === asset.categoryId) return asset;
      changed += 1;
      return { ...asset, categoryId: targetCategoryId };
    });
    if (changed > 0) updateStore(set, { ...state, assets });
    return changed;
  },

  addCategory: (libraryId, name, parentId) => {
    const state = get();
    const value = name.trim();
    if (!value || !state.libraries.some((library) => library.id === libraryId)) return '';
    const normalizedParentId = parentId || null;
    if (state.categories.some((category) =>
      category.libraryId === libraryId && category.parentId === normalizedParentId && category.name === value
    )) return '';
    const category: AssetCategory = {
      id: createId('category'),
      libraryId,
      name: value,
      parentId: normalizedParentId,
      createdAt: Date.now(),
    };
    updateStore(set, { ...state, categories: [...state.categories, category] });
    return category.id;
  },

  renameCategory: (categoryId, name) => {
    const value = name.trim();
    if (!value) return;
    const state = get();
    const current = state.categories.find((category) => category.id === categoryId);
    if (!current || current.builtin || state.categories.some((category) =>
      category.id !== categoryId
      && category.libraryId === current.libraryId
      && category.parentId === current.parentId
      && category.name === value
    )) return;
    updateStore(set, {
      ...state,
      categories: state.categories.map((category) =>
        category.id === categoryId ? { ...category, name: value } : category
      ),
    });
  },

  deleteCategory: (categoryId) => {
    const state = get();
    const category = state.categories.find((item) => item.id === categoryId);
    if (!category || category.builtin) return;
    // 收集该分组及所有子分组的 id
    const idsToDelete = new Set<string>([categoryId]);
    let changed = true;
    while (changed) {
      changed = false;
      state.categories.forEach((category) => {
        if (category.parentId && idsToDelete.has(category.parentId) && !idsToDelete.has(category.id)) {
          idsToDelete.add(category.id);
          changed = true;
        }
      });
    }
    updateStore(set, {
      ...state,
      categories: state.categories.filter((category) => !idsToDelete.has(category.id)),
      assets: state.assets.map((asset) =>
        asset.categoryId && idsToDelete.has(asset.categoryId) ? { ...asset, categoryId: null } : asset
      ),
    });
  },

  moveAssetsToCategory: (assetIds, categoryId) => {
    const ids = new Set(assetIds);
    const state = get();
    const target = categoryId ? state.categories.find((category) => category.id === categoryId) : null;
    if (categoryId && !target) return;
    updateStore(set, {
      ...state,
      assets: state.assets.map((asset) =>
        ids.has(asset.id) && (!target || asset.libraryId === target.libraryId)
          ? { ...asset, categoryId }
          : asset
      ),
    });
  },
}));

export type { LibraryAsset };
